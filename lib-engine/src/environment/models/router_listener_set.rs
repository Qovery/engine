//! One ListenerSet per hostname, used by the `PER_HOSTNAME_LISTENER_SET` routing mode.
//!
//! The identity of a ListenerSet and of its Helm release is derived from the normalized hostname only.
//! Core refuses to attach the same hostname to two routers, so a hostname has a single router at a time.
//! The engine does not trust that silently: a release owned by another router is never taken over,
//! see `router_listener_set_ownership`.
//!
//! The ListenerSet does not issue anything. The chart renders an explicit cert-manager `Certificate` next to it,
//! and that Certificate owns the TLS Secret and its renewals.

use crate::environment::models::router::RouterError;
use crate::io_models::models::CustomDomain;
use serde::Serialize;
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

/// Prefix of every Helm release and ListenerSet created by this mode.
const RELEASE_PREFIX: &str = "listenerset";
pub(crate) const HASH_HEX_CHARS: usize = 16;
const MAX_HOSTNAME_LENGTH: usize = 253;
const MAX_LABEL_LENGTH: usize = 63;

/// A single-hostname ListenerSet, applied by the router that serves the hostname.
#[derive(Serialize, Clone, Debug, Eq, PartialEq)]
pub(crate) struct HostnameListenerSet {
    /// Lowercase hostname without a trailing dot.
    pub hostname: String,
    /// Helm release and ListenerSet name. Depends on the hostname only.
    pub name: String,
    pub tls_secret_name: String,
    /// Namespaces where the routes using this hostname live. A ListenerSet only accepts routes of its own namespace.
    pub namespaces: BTreeSet<String>,
}

/// Lowercases the hostname and removes the trailing dot of a fully qualified name.
pub(crate) fn normalize_hostname(hostname: &str) -> String {
    let lowercase = hostname.trim().to_ascii_lowercase();
    lowercase.strip_suffix('.').unwrap_or(&lowercase).to_string()
}

/// Name of the Helm release and of the ListenerSet for an already normalized hostname.
pub(crate) fn listener_set_name(normalized_hostname: &str) -> String {
    let digest = Sha256::digest(normalized_hostname.as_bytes());
    let hash: String = digest.iter().map(|byte| format!("{byte:02x}")).collect();
    format!("{RELEASE_PREFIX}-{}", &hash[..HASH_HEX_CHARS])
}

/// Whether a release name has the shape of `listener_set_name`, `listenerset-<16 hex>`.
pub(crate) fn is_hostname_release_name(release_name: &str) -> bool {
    release_name
        .strip_prefix(RELEASE_PREFIX)
        .and_then(|rest| rest.strip_prefix('-'))
        .is_some_and(|hash| hash.len() == HASH_HEX_CHARS && hash.bytes().all(|byte| byte.is_ascii_hexdigit()))
}

/// Names generated by Qovery for the cluster (`rustrocks.me` domains) stay on the Gateway listener.
fn is_platform_hostname(hostname: &str, default_domain: &str, cluster_domain: &str) -> bool {
    let default_domain = normalize_hostname(default_domain);
    let cluster_domain = normalize_hostname(cluster_domain);
    let on_cluster_domain = |domain: &str| {
        !domain.is_empty()
            && (hostname == domain
                || hostname.ends_with(&format!(".{domain}"))
                // custom domains set on the cluster domain get their port name joined with a dash
                || hostname.ends_with(&format!("-{domain}")))
    };
    on_cluster_domain(&cluster_domain) || on_cluster_domain(&default_domain)
}

fn validate_hostname(hostname: &str) -> Result<(), RouterError> {
    let invalid =
        |reason: &str| RouterError::InvalidConfig(format!("hostname `{hostname}` cannot get a ListenerSet: {reason}"));

    if hostname.is_empty() || hostname.len() > MAX_HOSTNAME_LENGTH {
        return Err(invalid("its length must be between 1 and 253 characters"));
    }
    for label in hostname.split('.') {
        let valid_characters = label
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-');
        if label.is_empty() || label.len() > MAX_LABEL_LENGTH {
            return Err(invalid("each label must be between 1 and 63 characters"));
        }
        if !valid_characters || label.starts_with('-') || label.ends_with('-') {
            return Err(invalid(
                "labels may only contain a-z, 0-9 and '-', and cannot start or end with '-'",
            ));
        }
    }
    Ok(())
}

/// Builds the ListenerSets of a router from the hostnames of its routes, as `(namespace, hostname)` pairs.
///
/// A hostname gets a ListenerSet when it is a non-wildcard custom domain that asks for a certificate,
/// or the `<port name>.<domain>` hostname of such a domain.
/// Platform hostnames and hostnames that only come from a wildcard domain are left out, they keep using the Gateway listener.
/// Custom port hostnames such as `p8000.example.com` are distinct hostnames and get their own ListenerSet.
pub(crate) fn plan_hostname_listener_sets<'a>(
    route_hostnames: impl IntoIterator<Item = (&'a str, &'a str)>,
    port_names: &[&str],
    custom_domains: &[CustomDomain],
    default_domain: &str,
    cluster_domain: &str,
) -> Result<Vec<HostnameListenerSet>, RouterError> {
    // A domain declared twice asks for a certificate as soon as one of its declarations does.
    let mut certificate_by_domain: BTreeMap<String, bool> = BTreeMap::new();
    for domain in custom_domains.iter().filter(|domain| !domain.is_wildcard()) {
        *certificate_by_domain
            .entry(normalize_hostname(&domain.domain))
            .or_default() |= domain.generate_certificate;
    }
    let port_names: Vec<String> = port_names.iter().map(|name| name.to_ascii_lowercase()).collect();
    // A declared domain follows its own setting. Anything else must be `<port name>.<certified domain>`.
    let asks_for_a_certificate = |hostname: &str| match certificate_by_domain.get(hostname) {
        Some(generate_certificate) => *generate_certificate,
        None => port_names.iter().any(|port_name| {
            hostname
                .strip_prefix(&format!("{port_name}."))
                .is_some_and(|domain| certificate_by_domain.get(domain) == Some(&true))
        }),
    };

    let mut namespaces_by_hostname: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for (namespace, hostname) in route_hostnames {
        let hostname = normalize_hostname(hostname);
        // Only the hostnames that come from a wildcard domain are left out. They never ask for a certificate here,
        // because `asks_for_a_certificate` only follows the non-wildcard domains. A hostname declared on its own,
        // such as `api.example.com` next to `*.example.com`, keeps its ListenerSet.
        if hostname.starts_with('*')
            || !asks_for_a_certificate(&hostname)
            || is_platform_hostname(&hostname, default_domain, cluster_domain)
        {
            continue;
        }
        validate_hostname(&hostname)?;
        namespaces_by_hostname
            .entry(hostname)
            .or_default()
            .insert(namespace.to_string());
    }

    let mut hostname_by_name: BTreeMap<String, String> = BTreeMap::new();
    let mut listener_sets = Vec::with_capacity(namespaces_by_hostname.len());
    for (hostname, namespaces) in namespaces_by_hostname {
        let name = listener_set_name(&hostname);
        if let Some(other_hostname) = hostname_by_name.insert(name.clone(), hostname.clone()) {
            return Err(RouterError::InvalidConfig(format!(
                "hostnames `{other_hostname}` and `{hostname}` resolve to the same ListenerSet release `{name}`"
            )));
        }
        listener_sets.push(HostnameListenerSet {
            tls_secret_name: format!("{name}-tls"),
            hostname,
            name,
            namespaces,
        });
    }
    Ok(listener_sets)
}

/// ListenerSet name of each hostname, per namespace. Routes use it to pick their ListenerSet parents.
pub(crate) fn listener_set_names_by_namespace(
    listener_sets: &[HostnameListenerSet],
) -> BTreeMap<String, BTreeMap<String, String>> {
    let mut names: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    for listener_set in listener_sets {
        for namespace in &listener_set.namespaces {
            names
                .entry(namespace.clone())
                .or_default()
                .insert(listener_set.hostname.clone(), listener_set.name.clone());
        }
    }
    names
}

#[cfg(test)]
mod tests {
    use super::{
        HostnameListenerSet, is_hostname_release_name, listener_set_name, listener_set_names_by_namespace,
        normalize_hostname, plan_hostname_listener_sets,
    };
    use crate::io_models::models::CustomDomain;
    use std::collections::BTreeSet;

    const CLUSTER_DOMAIN: &str = "abc.rustrocks.me";
    const DEFAULT_DOMAIN: &str = "zrouter01.abc.rustrocks.me";
    const ENV_NAMESPACE: &str = "zenv-app";

    fn custom_domain(domain: &str, generate_certificate: bool) -> CustomDomain {
        CustomDomain {
            domain: domain.to_string(),
            target_domain: "".to_string(),
            generate_certificate,
            use_cdn: false,
        }
    }

    fn plan(
        hostnames: &[&str],
        custom_domains: &[CustomDomain],
    ) -> Result<Vec<HostnameListenerSet>, crate::environment::models::router::RouterError> {
        plan_hostname_listener_sets(
            hostnames.iter().map(|hostname| (ENV_NAMESPACE, *hostname)),
            &["p80", "p8000"],
            custom_domains,
            DEFAULT_DOMAIN,
            CLUSTER_DOMAIN,
        )
    }

    fn hostnames(listener_sets: &[HostnameListenerSet]) -> Vec<&str> {
        listener_sets.iter().map(|set| set.hostname.as_str()).collect()
    }

    #[test]
    fn normalization_lowercases_and_removes_the_trailing_dot() {
        assert_eq!(normalize_hostname("Api.Example.COM."), "api.example.com");
        assert_eq!(normalize_hostname("api.example.com"), "api.example.com");
    }

    #[test]
    fn the_same_hostname_always_resolves_to_the_same_release() {
        let domains = [custom_domain("api.example.com", true)];
        let first = plan(&["api.example.com"], &domains).unwrap();
        let again = plan(&["API.example.com."], &domains).unwrap();
        let reordered = plan(&["api.example.com", "API.example.com", "api.example.com."], &domains).unwrap();

        assert_eq!(first, again);
        assert_eq!(first, reordered);
        assert_eq!(first.len(), 1);
        assert_eq!(first[0].name, listener_set_name("api.example.com"));
        assert_eq!(first[0].tls_secret_name, format!("{}-tls", first[0].name));
    }

    #[test]
    fn identity_is_derived_from_the_normalized_hostname_only() {
        let domains = [custom_domain("api.example.com", true)];
        let listener_sets = plan(&["Api.Example.COM."], &domains).unwrap();

        // Pinned on purpose: changing the derivation renames every release already deployed.
        assert_eq!(listener_sets[0].name, "listenerset-d0c43d3885064d9a");
        assert_eq!(
            listener_sets[0].name,
            listener_set_name(&normalize_hostname("Api.Example.COM."))
        );
        assert_ne!(listener_set_name("api.example.com"), listener_set_name("api.example.org"));
    }

    #[test]
    fn only_names_derived_from_a_hostname_have_the_hostname_release_shape() {
        assert!(is_hostname_release_name(&listener_set_name("api.example.com")));
        assert!(!is_hostname_release_name("listenerset-zrouter01-0123456789abcdef"));
        assert!(!is_hostname_release_name("listenerset-0123456789abcde"));
        assert!(!is_hostname_release_name("listenerset-0123456789abcdefg"));
        assert!(!is_hostname_release_name("router-zrouter01"));
    }

    #[test]
    fn identity_is_a_valid_helm_release_name() {
        let name = listener_set_name("a-very-long-hostname.with.many.labels.example.com");

        assert!(name.len() <= 53, "Helm release names are limited to 53 characters: {name}");
        assert_eq!(name, name.to_ascii_lowercase());
    }

    #[test]
    fn primary_and_port_hostnames_get_distinct_listener_sets_even_with_a_single_port() {
        let domains = [custom_domain("test.example.com", true)];
        let listener_sets = plan(&["test.example.com", "p8000.test.example.com"], &domains).unwrap();

        assert_eq!(hostnames(&listener_sets), vec!["p8000.test.example.com", "test.example.com"]);
        assert_ne!(listener_sets[0].name, listener_sets[1].name);
        assert_ne!(listener_sets[0].tls_secret_name, listener_sets[1].tls_secret_name);
    }

    #[test]
    fn every_listener_set_has_a_single_hostname() {
        let domains = [
            custom_domain("a.example.com", true),
            custom_domain("b.example.com", true),
        ];
        let listener_sets = plan(&["a.example.com", "p80.a.example.com", "b.example.com"], &domains).unwrap();

        let names: BTreeSet<&str> = listener_sets.iter().map(|set| set.name.as_str()).collect();
        assert_eq!(names.len(), 3, "one release per hostname");
    }

    #[test]
    fn platform_generated_hostnames_are_excluded() {
        let domains = [custom_domain("api.example.com", true)];
        let listener_sets = plan(
            &[
                DEFAULT_DOMAIN,
                "p80-zrouter01.abc.rustrocks.me",
                "p80-zrouter01-gtw.abc.rustrocks.me",
                "api.example.com",
            ],
            &domains,
        )
        .unwrap();

        assert_eq!(hostnames(&listener_sets), vec!["api.example.com"]);
    }

    #[test]
    fn custom_domains_set_on_the_cluster_domain_are_excluded() {
        let domains = [custom_domain("shop.abc.rustrocks.me", true)];
        let listener_sets = plan(&["shop.abc.rustrocks.me", "p80-shop.abc.rustrocks.me"], &domains).unwrap();

        assert!(listener_sets.is_empty(), "{listener_sets:?}");
    }

    #[test]
    fn a_hostname_that_only_ends_like_the_cluster_domain_is_not_a_platform_hostname() {
        let domains = [
            custom_domain("myabc.rustrocks.me.example.org", true),
            custom_domain("notabc.rustrocks.me", true),
        ];
        let listener_sets = plan(&["myabc.rustrocks.me.example.org", "notabc.rustrocks.me"], &domains).unwrap();

        assert_eq!(
            hostnames(&listener_sets),
            vec!["myabc.rustrocks.me.example.org", "notabc.rustrocks.me"]
        );
    }

    #[test]
    fn wildcard_hostnames_are_excluded() {
        let domains = [custom_domain("*.example.com", true)];
        let listener_sets = plan(
            &["*.example.com", "example.com", "p80.example.com", "app.example.com"],
            &domains,
        )
        .unwrap();

        assert!(listener_sets.is_empty(), "{listener_sets:?}");
    }

    #[test]
    fn a_declared_hostname_keeps_its_listener_set_next_to_a_wildcard_domain() {
        let domains = [
            custom_domain("*.example.com", true),
            custom_domain("api.example.com", true),
        ];
        let listener_sets = plan(
            &[
                "*.example.com",
                "example.com",
                "app.example.com",
                "p80.example.com",
                "api.example.com",
                "p80.api.example.com",
            ],
            &domains,
        )
        .unwrap();

        assert_eq!(hostnames(&listener_sets), vec!["api.example.com", "p80.api.example.com"]);
    }

    #[test]
    fn a_declared_hostname_without_certificate_is_still_excluded_next_to_a_wildcard_domain() {
        let domains = [
            custom_domain("*.example.com", true),
            custom_domain("api.example.com", false),
        ];
        let listener_sets = plan(&["api.example.com", "p80.api.example.com"], &domains).unwrap();

        assert!(listener_sets.is_empty(), "{listener_sets:?}");
    }

    #[test]
    fn wildcard_exclusion_does_not_drop_the_other_custom_domains_of_the_router() {
        let domains = [
            custom_domain("*.example.com", true),
            custom_domain("api.example.org", true),
        ];
        let listener_sets = plan(&["*.example.com", "p80.example.com", "api.example.org"], &domains).unwrap();

        assert_eq!(hostnames(&listener_sets), vec!["api.example.org"]);
    }

    #[test]
    fn hostnames_without_certificate_generation_are_excluded() {
        let domains = [
            custom_domain("api.example.com", false),
            custom_domain("www.example.com", true),
        ];
        let listener_sets = plan(&["api.example.com", "p80.api.example.com", "www.example.com"], &domains).unwrap();

        assert_eq!(hostnames(&listener_sets), vec!["www.example.com"]);
    }

    #[test]
    fn a_declared_domain_without_certificate_stays_excluded_when_a_certified_parent_exists() {
        let domains = [
            custom_domain("example.com", true),
            custom_domain("www.example.com", false),
        ];
        let listener_sets = plan(
            &[
                "example.com",
                "www.example.com",
                "p80.example.com",
                "p80.www.example.com",
            ],
            &domains,
        )
        .unwrap();

        assert_eq!(hostnames(&listener_sets), vec!["example.com", "p80.example.com"]);
    }

    #[test]
    fn a_subdomain_that_is_not_a_port_name_is_not_a_port_hostname() {
        let domains = [custom_domain("example.com", true)];
        let listener_sets = plan(&["example.com", "other.example.com"], &domains).unwrap();

        assert_eq!(hostnames(&listener_sets), vec!["example.com"]);
    }

    #[test]
    fn route_hostnames_unrelated_to_a_custom_domain_are_excluded() {
        let domains = [custom_domain("api.example.com", true)];
        let listener_sets = plan(&["other.example.com", "a.b.api.example.com"], &domains).unwrap();

        assert!(listener_sets.is_empty(), "{listener_sets:?}");
    }

    #[test]
    fn invalid_hostnames_are_rejected_with_the_hostname_in_the_error() {
        let long_label = "a".repeat(64);
        for hostname in [
            "api_internal.example.com",
            "-api.example.com",
            "api-.example.com",
            "ap i.example.com",
            "api..example.com",
            "bücher.example.com",
            &format!("{long_label}.example.com"),
        ] {
            let domains = [custom_domain(hostname, true)];
            let error = plan(&[hostname], &domains).expect_err(hostname).to_string();
            assert!(error.contains(&hostname.to_ascii_lowercase()), "{error}");
        }
    }

    #[test]
    fn a_hostname_served_in_several_namespaces_is_one_release_with_one_listener_set_per_namespace() {
        let domains = [custom_domain("api.example.com", true)];
        let listener_sets = plan_hostname_listener_sets(
            [
                ("ns-a", "api.example.com"),
                ("ns-b", "API.example.com"),
                ("ns-a", "api.example.com"),
            ],
            &[],
            &domains,
            DEFAULT_DOMAIN,
            CLUSTER_DOMAIN,
        )
        .unwrap();

        assert_eq!(listener_sets.len(), 1);
        assert_eq!(
            listener_sets[0].namespaces,
            BTreeSet::from(["ns-a".to_string(), "ns-b".to_string()])
        );

        let names = listener_set_names_by_namespace(&listener_sets);
        assert_eq!(names["ns-a"]["api.example.com"], listener_sets[0].name);
        assert_eq!(names["ns-b"]["api.example.com"], listener_sets[0].name);
    }
}
